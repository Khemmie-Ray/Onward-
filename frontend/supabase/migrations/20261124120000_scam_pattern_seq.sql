
ALTER TABLE public.scam_patterns
  ADD COLUMN IF NOT EXISTS seq BIGINT GENERATED BY DEFAULT AS IDENTITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_indexes
    WHERE schemaname = 'public' AND indexname = 'scam_patterns_seq_key'
  ) THEN
    WITH ordered AS (
      SELECT id, row_number() OVER (ORDER BY created_at, ctid) AS rn
      FROM public.scam_patterns
    )
    UPDATE public.scam_patterns p
    SET seq = o.rn
    FROM ordered o
    WHERE p.id = o.id;

    PERFORM setval(
      pg_get_serial_sequence('public.scam_patterns', 'seq'),
      (SELECT COALESCE(max(seq), 1) FROM public.scam_patterns)
    );
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS scam_patterns_seq_key
  ON public.scam_patterns (seq);